export type TaskBucket = 'overdue' | 'today' | 'this_week' | 'later' | 'completed'

export interface BucketableTask {
  status: string
  dueDate: string | null
  alarmDate: string | null
  completedAt: string | null
  autoGenerated?: boolean
  automationKey?: string | null
  project?: {
    name: string
    poNumber?: string | null
    startDate?: string | null
    status?: string | null
    materialsPlannedTotal?: number
    materialsDispatchedTotal?: number
  } | null
}

function todayLocal(): Date {
  const n = new Date()
  return new Date(n.getFullYear(), n.getMonth(), n.getDate())
}

function parseLocal(dateStr: string): Date | null {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(dateStr)
  if (!m) return null
  return new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]))
}

export function daysBetween(a: Date, b: Date): number {
  const ms = 24 * 60 * 60 * 1000
  return Math.round((a.getTime() - b.getTime()) / ms)
}

export function getEffectiveDueDate(task: BucketableTask): string | null {
  return task.dueDate || task.alarmDate || null
}

export function bucketTask(task: BucketableTask, today: Date = todayLocal()): TaskBucket {
  if (task.status === 'completed') return 'completed'
  const dueStr = getEffectiveDueDate(task)
  if (!dueStr) return 'later'
  const due = parseLocal(dueStr)
  if (!due) return 'later'
  const days = daysBetween(due, today)
  if (days < 0) return 'overdue'
  if (days <= 1) return 'today'
  if (days <= 7) return 'this_week'
  return 'later'
}

