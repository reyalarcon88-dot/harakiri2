export function formatRelativeDue(dateStr: string, today: Date = todayLocal()): string {
  const due = parseLocal(dateStr)
  if (!due) return ''
  const days = daysBetween(due, today)
  if (days < 0) return `Vencido ${days}d`
  if (days === 0) return 'Hoy'
  if (days === 1) return 'Mañana'
  if (days <= 7) return `En ${days} días`
  // Show short date for far-future
  return new Intl.DateTimeFormat('es', { day: 'numeric', month: 'short' }).format(due)
}

export function formatStartsIn(daysToStart: number): string {
  if (daysToStart < 0) return `Inició hace ${Math.abs(daysToStart)} días`
  if (daysToStart === 0) return 'Inicia hoy'
  if (daysToStart === 1) return 'Inicia mañana'
  return `Inicia en ${daysToStart} días`
}

export interface EnrichedContext {
  contextLine: string
  dispatchedPct?: number
}

export function enrichAutoTask(task: BucketableTask, today: Date = todayLocal()): EnrichedContext | null {
  if (!task.autoGenerated || !task.project) return null
  const project = task.project
  const startDate = project.startDate ? parseLocal(project.startDate) : null
  const daysToStart = startDate ? daysBetween(startDate, today) : null
  const planned = project.materialsPlannedTotal ?? 0
  const dispatched = project.materialsDispatchedTotal ?? 0
  const pct = planned > 0 ? Math.round((dispatched / planned) * 100) : 0
  const startsInLine = daysToStart !== null ? formatStartsIn(daysToStart) : null

  const parts: (string | null)[] = []

  switch (task.automationKey) {
    case 'need_engineering':
      parts.push('Sin documento de ingeniería')
      break
    case 'need_materials_list':
      parts.push('Sin lista de materiales')
      break
    case 'need_client_info':
      parts.push('Falta información del cliente')
      break
    case 'order_materials':
      parts.push(startsInLine, planned > 0 ? `${pct}% despachado` : null)
      break
    case 'start_project_notice':
      parts.push(
        startsInLine,
        project.status ? `Status: ${project.status}` : null,
      )
      break
    case 'confirm_vendor':
      parts.push(startsInLine, 'Pedido pendiente de confirmación')
      break
    case 'verify_materials_received':
      parts.push(startsInLine, planned > 0 ? `${pct}% recibido` : null)
      break
    case 'followup_materials':
      parts.push(planned > 0 ? `${100 - pct}% pendiente de despacho` : 'Materiales pendientes')
      break
    case 'crew_confirm_materials':
      parts.push(startsInLine, planned > 0 ? `${pct}% despachado` : null)
      break
    case 'resolve_minor_items':
      parts.push('Items menores pendientes')
      break
    case 'jobsite_check':
      parts.push('Revisar incidencias del proyecto')
      break
    case 'resolve_vs_engineering':
      parts.push('Resolver cambios vs plano')
      break
    default:
      return null
  }

  const contextLine = parts.filter(Boolean).join(' · ')
  if (!contextLine) return null
  return { contextLine, dispatchedPct: planned > 0 ? pct : undefined }
}

