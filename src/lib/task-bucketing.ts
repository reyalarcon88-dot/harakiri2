export function isDateWithinNDays(dateStr: string | null, n: number, today: Date = todayLocal()): boolean {
  if (!dateStr) return false
  const d = parseLocal(dateStr)
  if (!d) return false
  const days = daysBetween(today, d)
  return days >= 0 && days <= n
}
